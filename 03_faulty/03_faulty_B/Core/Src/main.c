/* 결함 진단용: 이론 4 '레지스터 5개' + lwIP 통계 */
static void print_diag(void)
{
  uint32_t csr = ETH->DMACSR, dsr = ETH->DMADSR;
  printf("--- diag @%lus ---\r\n", (unsigned long)(HAL_GetTick() / 1000U));
  printf("ETH_DMACSR=0x%08lX (RI=%lu RBU=%lu FBE=%lu)  ETH_DMADSR=0x%08lX (RPS0=%lu TPS0=%lu)\r\n",
         csr, (csr >> 6) & 1U, (csr >> 7) & 1U, (csr >> 12) & 1U, dsr, (dsr >> 8) & 0xFU, (dsr >> 12) & 0xFU);
  printf("ETH_MACCR=0x%08lX (FES=%lu DM=%lu)\r\n", ETH->MACCR, (ETH->MACCR >> 14) & 1U, (ETH->MACCR >> 13) & 1U);
#if MEMP_STATS
  printf("RX_POOL used=%u/%u err=%u   NETBUF used=%u err=%u\r\n",
         (unsigned)memp_RX_POOL.stats->used, (unsigned)memp_RX_POOL.num, (unsigned)memp_RX_POOL.stats->err,
         (unsigned)lwip_stats.memp[MEMP_NETBUF]->used, (unsigned)lwip_stats.memp[MEMP_NETBUF]->err);
#endif
#if MEM_STATS
  printf("heap used=%u max=%u err=%u (MEM_SIZE %u @0x%08lX)\r\n", (unsigned)lwip_stats.mem.used,
         (unsigned)lwip_stats.mem.max, (unsigned)lwip_stats.mem.err, (unsigned)MEM_SIZE,
         (unsigned long)LWIP_RAM_HEAP_POINTER);
#endif
  printf("FreeRTOS heap free=%u (min %u)\r\n", (unsigned)xPortGetFreeHeapSize(),
         (unsigned)xPortGetMinimumEverFreeHeapSize());
}
