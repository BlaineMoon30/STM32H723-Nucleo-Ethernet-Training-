/**
  * @brief  Function implementing the defaultTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void *argument)
{
  /* init code for LWIP */
  MX_LWIP_Init();
  /* USER CODE BEGIN 5 */
  printf("\r\n=== Hands-on 3: FreeRTOS + lwIP (netconn / httpd) %s===\r\n",
         "[faulty B] ");
  printf("IP %s  echo :%u  http :80  (B1 = diag)\r\n", ip4addr_ntoa(netif_ip4_addr(&gnetif)), (unsigned)ECHO_PORT);

  const osThreadAttr_t srv_attr = { .name = "server", .stack_size = 1024 * 4, .priority = osPriorityNormal };
  osThreadNew(server_task, NULL, &srv_attr);          /* Step 1: 에코 서버 */
  web_init();                                         /* Step 2: httpd + SSI/CGI */
#if APP_USE_MQTT
  const osThreadAttr_t mq_attr = { .name = "mqtt", .stack_size = 1024 * 4, .priority = osPriorityBelowNormal };
  osThreadNew(mqtt_task, NULL, &mq_attr);             /* Step 3 (선택) */
#endif

  uint8_t link_prev = 0xFFU;
  uint32_t t_led = 0;
  /* Infinite loop */
  for(;;)
  {
    uint8_t up = netif_is_link_up(&gnetif) ? 1U : 0U;
    if (up != link_prev)                               /* 링크 변화는 여기서 출력 (EthLink 스레드 스택이 작음) */
    {
      char s[8];
      app_link_str(s, sizeof s);
      printf("Link %s\r\n", up ? s : "DOWN");
      link_prev = up;
      if (up) { BSP_LED_On(LED_YELLOW); } else { BSP_LED_Off(LED_YELLOW); }   /* LD2 = 링크 */
    }
    if ((HAL_GetTick() - t_led) >= 500U)
    {
      t_led = HAL_GetTick();
      if (!led_manual) { BSP_LED_Toggle(LED_GREEN); }  /* LD1 점멸 = 스케줄러 동작 중 */
    }
    if (stat_req) { stat_req = 0U; print_diag(); }
    osDelay(50);
  }
  /* USER CODE END 5 */
}

