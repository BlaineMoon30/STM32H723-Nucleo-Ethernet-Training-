int app_link_str(char *out, size_t len)
{
  ETH_MACConfigTypeDef mc;
  if (!netif_is_link_up(&gnetif)) { return snprintf(out, len, "DOWN"); }
  HAL_ETH_GetMACConfig(&heth, &mc);
  return snprintf(out, len, "%s%s", (mc.Speed == ETH_SPEED_100M) ? "100" : "10",
                  (mc.DuplexMode == ETH_FULLDUPLEX_MODE) ? "F" : "H");
}

